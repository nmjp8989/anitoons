#!/usr/bin/env python3
"""Compile standalone scene SVGs into an offline-friendly catalogue."""
import json
import re
from pathlib import Path
import xml.etree.ElementTree as ET
ROOT = Path(__file__).resolve().parents[1]
def build():
    scenes = {}
    for file in sorted((ROOT / 'scenes').glob('*.svg')):
        root = ET.fromstring(file.read_text())
        if root.tag != '{http://www.w3.org/2000/svg}svg' or root.get('viewBox') != '0 0 1280 800':
            raise ValueError(f'{file.name}: expected SVG with viewBox="0 0 1280 800"')
        for element in root.iter():
            tag = element.tag.split('}')[-1]
            if tag in {'script', 'foreignObject', 'image', 'use'}:
                raise ValueError(f'{file.name}: unsupported element {tag}; use self-contained vector paths')
            for key, value in element.attrib.items():
                if key.lower().startswith('on') or 'href' in key or '@import' in value or 'javascript:' in value.lower():
                    raise ValueError(f'{file.name}: external or active content is unsupported')
            if tag == 'style':
                raise ValueError(f'{file.name}: use presentation attributes instead of style blocks')
        title = root.find('{http://www.w3.org/2000/svg}title')
        art = file.read_text()
        prefix = 'setting-' + file.stem + '-'
        art = re.sub(r'id="([^"]+)"', lambda m: 'id="'+prefix+m[1]+'"', art)
        art = re.sub(r'url\(#([^)]*)\)', lambda m: 'url(#'+prefix+m[1]+')', art)
        scenes[file.stem] = {'label': title.text if title is not None else file.stem.replace('-', ' ').title(), 'svg': art}
    output = '/* Generated by tools/build_scene_catalog.py */\nwindow.UMTO_SCENES = ' + json.dumps(scenes, ensure_ascii=False).replace('<', '\\u003c') + ';\n'
    (ROOT / 'scenes' / 'catalog.js').write_text(output)
    print(f'Built {len(scenes)} scenes')
if __name__ == '__main__':
    build()
