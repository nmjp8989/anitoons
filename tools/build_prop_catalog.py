#!/usr/bin/env python3
"""Compile self-contained prop SVGs and matching anchor metadata."""
import json
from pathlib import Path
import xml.etree.ElementTree as ET
ROOT=Path(__file__).resolve().parents[1]
def build():
    assets={}
    for svg in sorted((ROOT/'props').glob('*.svg')):
        metadata=json.loads(svg.with_suffix('.json').read_text())
        root=ET.fromstring(svg.read_text())
        assert root.tag=='{http://www.w3.org/2000/svg}svg',svg.name
        assert root.get('viewBox')==metadata['viewBox'],svg.name
        for e in root.iter():
            assert e.tag.split('}')[-1] not in {'script','foreignObject','image','use','style'},svg.name
            assert all(not k.lower().startswith('on') and 'href' not in k for k in e.attrib),svg.name
        for anchor in metadata.get('anchors',{}).values():
            assert len(anchor['matrix'])==6 and all(isinstance(x,(int,float)) for x in anchor['matrix']),svg.name
            assert isinstance(anchor['accepts'],list) and anchor['capacity']>0,svg.name
        assets[svg.stem]={**metadata,'svg':svg.read_text()}
    (ROOT/'props/catalog.js').write_text('/* Generated by tools/build_prop_catalog.py */\nwindow.UMTO_PROPS='+json.dumps(assets).replace('<','\\u003c')+';\n')
    print(f'Built {len(assets)} props')
if __name__=='__main__':build()
