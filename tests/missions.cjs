'use strict';
const assert=require('node:assert/strict');
const Engine=require('../missions/mission-engine.js');
const mission=require('../missions/mission.json');
const engine=new Engine(mission),state=engine.state;
assert.equal(engine.trigger('click:go').ok,false,'Cannot finish without key and rider');
assert.equal(engine.trigger('click:cupboard').ok,false,'Chai gates the cupboard clue');
assert.equal(engine.trigger('unknown').ok,false);
assert.equal(engine.trigger('drop:cup:character').ok,true);
assert.equal(state.flags.tea,true);
engine.trigger('drop:character:sofa');assert.equal(state.pose,'sit');
assert.equal(engine.trigger('click:cupboard').ok,true);assert.equal(state.visible.key,true);
engine.trigger('click:key');engine.trigger('click:key');assert.deepEqual(state.inventory,['key'],'Repeated clicks do not duplicate inventory');
assert.equal(engine.trigger('click:go').ok,false,'Having key is not enough');
engine.trigger('drop:key:scooter');assert.equal(state.flags.unlocked,true);
assert.equal(engine.trigger('click:go').ok,false,'Must mount before departure');
engine.trigger('drop:character:scooter');assert.equal(state.flags.mounted,true);
const ending=engine.trigger('click:go');assert.equal(ending.ok,true);assert.equal(state.complete,false,'Ending waits for the cutscene');engine.finish();assert.equal(state.complete,true);assert(ending.actions.indexOf('cutscene:departure')<ending.actions.indexOf('ending:complete'));
engine.reset();assert.equal(engine.state.complete,false);assert.deepEqual(engine.state.inventory,[]);assert.deepEqual(engine.state.flags,{});
for(const choice of mission.choices)assert(['cupboard','outside'].includes(choice.action));
console.log('PASS · mission gating, object interactions, duplicate inventory, ending sequence, reset');
